# ── Загружаем существующий core.json ──
with open('assets/data/lexicon/core.json', 'r', encoding='utf-8') as f:
    core = json.load(f)

existing_ids = {c['id'] for c in core}
existing_strongs = {c['strong'] for c in core}

# ── Загружаем frequency.json ──
with open('assets/data/lexicon/frequency.json', 'r', encoding='utf-8') as f:
    freq_list = json.load(f)

freq_by_strong = {f['strong']: f for f in freq_list}

# ── Создаём новые записи ──
new_entries = []
for (strong, eid, gloss, pos, ru_matches, ru_exclude) in translations:
    if strong in existing_strongs:
        print(f'SKIP: G{strong} already in core.json')
        continue
    if eid in existing_ids:
        # Add suffix to make unique
        eid = f"{eid}-alt"
        if eid in existing_ids:
            print(f'DUPLICATE ID: {eid}')
            continue

    freq = freq_by_strong.get(strong, {})
    entry = {
        "id": eid,
        "lemma": "",  # Will fill from strongs-dictionary or frequency
        "translit": "",
        "strong": strong,
        "gloss": gloss,
        "pos": pos,
        "ruMatches": ru_matches,
        "ruExclude": ru_exclude,
        "freqNT": freq.get('count', 0),
        "refs": []
    }
    new_entries.append(entry)

print(f'New entries: {len(new_entries)}')

# ── Заполняем lemma и translit из strongs-dictionary.json ──
with open('data-sources/strongs-dictionary.json', 'r', encoding='utf-8') as f:
    strongs_dict = json.load(f)

strongs_by_strong = {s['strong']: s for s in strongs_dict}

for entry in new_entries:
    sd = strongs_by_strong.get(entry['strong'], {})
    if sd:
        entry['lemma'] = sd.get('lemma', '')
        entry['translit'] = sd.get('translit', '')
    else:
        # Fallback to frequency list
        freq = freq_by_strong.get(entry['strong'], {})
        entry['lemma'] = freq.get('lemma', '')
        entry['translit'] = freq.get('translit', '')

# ── Сливаем с существующим core.json ──
core.extend(new_entries)

